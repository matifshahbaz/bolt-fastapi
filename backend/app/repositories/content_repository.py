    def _set_text_lesson_article(self, lesson_id: str, article: LessonArticle) -> None:
        for module in self._featured_course.modules:
            for lesson in module.lessons:
                if lesson.id == lesson_id and lesson.kind == "text":
                    lesson.article = article
                    return

