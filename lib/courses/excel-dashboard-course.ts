import type { Course, CourseLesson, CourseModule } from '@/lib/data';
import { COURSE_PRICE } from '@/lib/course-policy';

type LessonSpec = {
  title: string;
  videoUid: string;
  duration: string;
};

function videoLesson(moduleId: string, lessonNumber: number, spec: LessonSpec): CourseLesson {
  return {
    id: `${moduleId}-v${lessonNumber}`,
    kind: 'video',
    title: spec.title,
    duration: spec.duration,
    videoUid: spec.videoUid,
  };
}

function courseModule(moduleNumber: number, title: string, lessonSpecs: LessonSpec[]): CourseModule {
  const moduleId = `excel-m${moduleNumber}`;

  return {
    id: moduleId,
    title: `ماڈیول ${moduleNumber} — ${title}`,
    lessons: lessonSpecs.map((spec, index) => videoLesson(moduleId, index + 1, spec)),
  };
}

