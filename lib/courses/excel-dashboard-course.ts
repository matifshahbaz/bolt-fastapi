import type { Course, CourseLesson, CourseModule } from '@/lib/data';
import { COURSE_PRICE } from '@/lib/course-policy';

function comingSoonVideoLesson(moduleId: string, lessonNumber: number, title: string): CourseLesson {
  return {
    id: `${moduleId}-v${lessonNumber}`,
    kind: 'video',
    title,
    duration: 'جلد دستیاب',
    comingSoon: true,
  };
}

function courseModule(
  moduleNumber: number,
  stage: string,
  title: string,
  lessonTitles: string[],
): CourseModule {
  const moduleId = `excel-m${moduleNumber}`;

  return {
    id: moduleId,
    stage,
    title: `ماڈیول ${moduleNumber} — ${title}`,
    lessons: lessonTitles.map((lessonTitle, index) => comingSoonVideoLesson(moduleId, index + 1, lessonTitle)),
  };
}

